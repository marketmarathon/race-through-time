    a(f"Compared {n_common} cells present in both. OWID prints 6 decimals: **{len(rd)}** cells differ only in the 6th or "
      f"7th decimal (\"rounding\", under 0.00001; never visible at one decimal). Real value differences: **{len(vd)}**; only "
      f"in WDI: **{len(wd)}**; only in OWID: **{len(ow)}**. OWID's copy is \"World Development Indicators 129\" (OWID "
      "lastUpdated 2026-07-27); WDI was updated 2026-10-08. Every difference, rounding included: "
      "`data/rtt-104/wdi_owid_differences.csv`. The video uses WDI only.")
    a("")
    for d in (vd + wd + ow)[:80]:
        a(f"- {name.get(d['iso3'], d['iso3'])} {d['year']}: WDI {one_dp(d['wdi']) if d['wdi'] else '-'} / OWID "
          f"{one_dp(d['owid']) if d['owid'] else '-'} ({d['difference']}{', ' + d['amount'] if d['amount'] else ''})")
    if len(vd + wd + ow) > 80:
        a(f"- … {len(vd + wd + ow) - 80} more in the CSV")
    a(f"- OWID entities with no World Bank economy code (not compared): {', '.join(owid_only) or 'none'}.")
    a("")

    # 14 running time
    a("## 14. Running time (estimate)")
    a("")
    n = len(years)
    a(f"{n} years: at 2 s per year **{2 * n} s**, at 3 s per year **{3 * n} s** of race. With an estimated 5 s title and "
      f"8 s closing card (not designed yet): about {(2 * n + 13) // 60} min {(2 * n + 13) % 60:02d} s and "
      f"{(3 * n + 13) // 60} min {(3 * n + 13) % 60:02d} s. These are estimates, not timings.")
    a("")

    # 15 checks
    a("## 15. Checks")
    a("")
